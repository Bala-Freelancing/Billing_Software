export const HOME_STATE_CODE = "33"; // Tamil Nadu

const STATE_CODES = new Set(STATES.map((s) => s.code));
export const isStateCode = (code: string) => STATE_CODES.has(code);
export const stateName = (code: string) => STATES.find((s) => s.code === code)?.name ?? code;

const GSTIN_SHAPE = /^[0-9]{2}[A-Z]{5}[0-9]{4}[A-Z][1-9A-Z]Z[0-9A-Z]$/;
const CHARSET = "0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZ";

/** Official GSTIN check digit (mod-36 over the first 14 characters). */
function gstinCheckChar(first14: string): string {
  let sum = 0;
  for (let i = 0; i < 14; i++) {
    const value = CHARSET.indexOf(first14[i] ?? "");
    const product = value * (i % 2 === 0 ? 1 : 2);
    sum += Math.floor(product / 36) + (product % 36);
  }
  return CHARSET[(36 - (sum % 36)) % 36] ?? "";
}

/** Returns null when valid, otherwise a human-readable reason. Expects an upper-cased value. */
export function gstinProblem(gstin: string): string | null {
  if (!GSTIN_SHAPE.test(gstin)) return "GSTIN must be 15 characters like 33ABCDE1234F1Z5";
  if (!isStateCode(gstin.slice(0, 2))) return "GSTIN starts with an unknown state code";
  if (gstinCheckChar(gstin.slice(0, 14)) !== gstin[14]) return "GSTIN check digit is wrong — please re-check it";
  return null;
}

/** WhatsApp number (91 + 10 digits) for an Indian mobile, or null if it isn't one. */
export function whatsAppNumber(phone: string): string | null {
  const d = phone.replace(/\D/g, "").replace(/^0+/, "");
  const ten = d.length === 12 && d.startsWith("91") ? d.slice(2) : d;
  return /^[6-9]\d{9}$/.test(ten) ? `91${ten}` : null;
}
